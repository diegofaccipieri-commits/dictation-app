/// One transcribed utterance, attributed to a speaker. For now the attribution is track-based:
/// "Você" = microphone track, "Outros" = system-audio track. Multi-speaker diarization of the
/// "Outros" track (via FluidAudio) is a follow-up.
struct MeetingSegment: Identifiable, Hashable, Codable {
    var id = UUID()
    let speaker: String
    let text: String
    let start: TimeInterval
    let end: TimeInterval

    var isMe: Bool { speaker == MeetingSegment.meLabel }
    static let meLabel = "Você"
    static let othersLabel = "Outros"
}

/// Persists a meeting transcript as a JSON sidecar next to the audio.
enum MeetingTranscriptStore {
    static func url(for id: String) -> URL {
        MeetingPaths.audioDir.appendingPathComponent("meeting_\(id)_transcript.json")
    }
    static func save(_ segments: [MeetingSegment], id: String) {
        guard let data = try? JSONEncoder().encode(segments) else { return }
        try? data.write(to: url(for: id), options: .atomic)
    }
    static func load(id: String) -> [MeetingSegment]? {
        guard let data = try? Data(contentsOf: url(for: id)) else { return nil }
        return try? JSONDecoder().decode([MeetingSegment].self, from: data)
    }
}

/// Produces a portable UTF-8 transcript that can be imported or pasted into other apps.
enum MeetingTranscriptExport {
    static func plainText(title: String, date: Date, segments: [MeetingSegment]) -> String {
        let dateFormatter = DateFormatter()
        dateFormatter.dateStyle = .long
        dateFormatter.timeStyle = .short

        let transcript = segments
            .sorted { $0.start < $1.start }
            .map { segment in
                "[\(MeetingTrimLogic.label(segment.start))] \(segment.speaker)\n\(segment.text)"
            }
            .joined(separator: "\n\n")

        return """
        \(title)
        \(dateFormatter.string(from: date))

        \(transcript)
        """
    }

    static func suggestedFileName(title: String, date: Date) -> String {
        let invalid = CharacterSet(charactersIn: "/:\\?%*|\"<>")
            .union(.newlines)
            .union(.controlCharacters)
        let cleanTitle = title
            .components(separatedBy: invalid)
            .joined(separator: " ")
            .replacingOccurrences(of: #"\s+"#, with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)

        let base: String
        if cleanTitle.isEmpty {
            let dateFormatter = DateFormatter()
            dateFormatter.locale = Locale(identifier: "en_US_POSIX")
            dateFormatter.dateFormat = "yyyy-MM-dd_HHmm"
            base = "reuniao-\(dateFormatter.string(from: date))"
        } else {
            base = cleanTitle
        }
        return "\(base)-transcricao.txt"
    }
}

/// Groups fine-grained whisper segments into readable paragraphs (new block on speaker change,
/// long pause, or length).
enum MeetingGrouping {
    static func cleanText(_ t: String) -> String {
        var s = t.replacingOccurrences(of: #"<\|[^|]*\|>"#, with: "", options: .regularExpression)
        s = s.replacingOccurrences(of: #"\s+"#, with: " ", options: .regularExpression)
        return s.trimmingCharacters(in: .whitespaces)
    }

    static func paragraphs(from segs: [MeetingSegment], gap: Double = 1.5, maxChars: Int = 500) -> [MeetingSegment] {
        let sorted = segs.sorted { $0.start < $1.start }
        guard let first = sorted.first else { return [] }
        var out: [MeetingSegment] = []
        var speaker = first.speaker
        var start = first.start
        var end = first.end
        var texts = [first.text]
        func flush() {
            let text = texts.joined(separator: " ")
                .replacingOccurrences(of: #"\s+"#, with: " ", options: .regularExpression)
                .trimmingCharacters(in: .whitespaces)
            if !text.isEmpty { out.append(MeetingSegment(speaker: speaker, text: text, start: start, end: end)) }
        }
        for seg in sorted.dropFirst() {
            let running = texts.joined(separator: " ").count
            if seg.speaker != speaker || (seg.start - end) >= gap || running >= maxChars {
                flush()
                speaker = seg.speaker; start = seg.start; end = seg.end; texts = [seg.text]
            } else {
                end = seg.end; texts.append(seg.text)
            }
        }
        flush()
        return out
    }
}

/// A compact RMS envelope for the 16 kHz WAV generated by `AudioDecoder`. It lets us reject
/// Whisper segments that were decoded entirely from digital silence without retaining full audio
/// in memory for long meetings.
private struct MeetingAudioEnergyEnvelope {
    private static let bucketDuration: TimeInterval = 0.1
    private static let minimumSpeechPeak: Float = 0.001
    private let buckets: [Float]

    init?(wav: URL) {
        do {
            let handle = try FileHandle(forReadingFrom: wav)
            defer { try? handle.close() }
            try handle.seek(toOffset: 44) // AudioDecoder writes a fixed 44-byte PCM WAV header.

            var levels: [Float] = []
            let samplesPerBucket = 1_600 // 100 ms at 16 kHz, mono, 16-bit PCM.
            while let data = try handle.read(upToCount: samplesPerBucket * 2), !data.isEmpty {
                let sampleCount = data.count / 2
                guard sampleCount > 0 else { continue }
                var sum: Float = 0
                for offset in stride(from: 0, to: sampleCount * 2, by: 2) {
                    let value = UInt16(data[offset]) | (UInt16(data[offset + 1]) << 8)
                    let sample = Float(Int16(bitPattern: value)) / Float(Int16.max)
                    sum += sample * sample
                }
                levels.append(sqrt(sum / Float(sampleCount)))
            }
            guard !levels.isEmpty else { return nil }
            buckets = levels
        } catch {
            return nil
        }
    }

    func containsSpeech(from start: TimeInterval, to end: TimeInterval) -> Bool {
        let startIndex = max(0, Int(floor(start / Self.bucketDuration)))
        let endIndex = min(buckets.count - 1,
                           max(startIndex, Int(ceil(max(end, start + Self.bucketDuration) / Self.bucketDuration))))
        guard startIndex < buckets.count else { return false }
        return buckets[startIndex...endIndex].contains { $0 >= Self.minimumSpeechPeak }
    }
}

/// Drives Whisper transcription of meetings, reusing the app's existing WhisperCppCLI + AudioDecoder.
/// Transcribes the mic and system tracks separately (labels "Você" / "Outros") and merges by time.
@MainActor
final class MeetingTranscriber: ObservableObject {
    static let shared = MeetingTranscriber()

    enum Status: Equatable {
        case idle, running(String), done, failed(String)
    }

    @Published private var statusById: [String: Status] = [:]
    @Published private var segmentsById: [String: [MeetingSegment]] = [:]

    func loadExisting(_ items: [MeetingItem]) {
        for item in items where segmentsById[item.id] == nil {
            if let segs = MeetingTranscriptStore.load(id: item.id), !segs.isEmpty {
                segmentsById[item.id] = segs
                statusById[item.id] = .done
            }
        }
    }

    func status(for id: String) -> Status { statusById[id] ?? .idle }
    func segments(for id: String) -> [MeetingSegment] { segmentsById[id] ?? [] }

    func contains(id: String, query: String) -> Bool {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return true }
        return segments(for: id).contains { MeetingSearch.matches($0, query: q) }
    }

    func matchCount(id: String, query: String) -> Int {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return 0 }
        return segments(for: id).filter { MeetingSearch.matches($0, query: q) }.count
    }

    func clear(id: String) {
        segmentsById.removeValue(forKey: id)
        statusById.removeValue(forKey: id)
    }

    func transcribe(_ item: MeetingItem, language: String) {
        failures.removeValue(forKey: item.id)
        if let current, current.auto {
            // The user asked for a meeting while the idle queue is busy: theirs goes first.
            worker?.cancel()
            queue.insert((item, language), at: 0)
            statusById[item.id] = .running("Na fila...")
            return
        }
        if current != nil {
            queue.append((item, language))
            statusById[item.id] = .running("Na fila...")
            return
        }
        run(item, language: language, auto: false)
    }

    private func run(_ item: MeetingItem, language: String, auto: Bool) {
        current = (item.id, auto)
        statusById[item.id] = .running("Preparando Whisper...")
        segmentsById[item.id] = []
        if auto { autoStatus = "Transcrevendo automaticamente: \(item.displayTitle)" }

        worker = Task {
            do {
                let urls = [item.micURL, item.systemURL].compactMap { $0 }
                statusById[item.id] = .running("Baixando áudio do Dropbox...")
                await Task.detached(priority: .utility) { urls.forEach(MeetingPaths.ensureLocal) }.value
                try Task.checkCancellation()

                var all: [MeetingSegment] = []
                try await transcribeTrack(item.micURL, speaker: MeetingSegment.meLabel,
                                          label: "sua voz", language: language, id: item.id, into: &all)
                try await transcribeTrack(item.systemURL, speaker: MeetingSegment.othersLabel,
                                          label: "os outros", language: language, id: item.id, into: &all)

                let grouped = MeetingGrouping.paragraphs(from: all)
                segmentsById[item.id] = grouped
                statusById[item.id] = grouped.isEmpty ? .failed("Nenhuma fala reconhecida.") : .done
                MeetingTranscriptStore.save(grouped, id: item.id)
                DictationDiagnostics.record("meeting_transcribed", fields: ["id": item.id, "auto": auto, "segments": grouped.count])
            } catch is CancellationError {
                // Paused by the user coming back (auto) or by a manual request; picked up again later.
                statusById[item.id] = .idle
                segmentsById.removeValue(forKey: item.id)
            } catch {
                statusById[item.id] = .failed(error.localizedDescription)
                failures[item.id, default: 0] += 1
                DictationDiagnostics.record("meeting_transcribe_failed", fields: ["id": item.id, "auto": auto, "error": error.localizedDescription])
            }
            current = nil
            worker = nil
            if auto { autoStatus = "" }
            if !queue.isEmpty {
                let (next, lang) = queue.removeFirst()
                run(next, language: lang, auto: false)
            } else {
                autoTick()
            }
        }
    }

    // MARK: Automatic transcription of every meeting, while the Mac is idle or overnight

    /// Set by the app: true while a dictation is recording or being transcribed.
    var isDictationBusy: () -> Bool = { false }
    /// Set by MeetingRecorder while a meeting is being recorded.
    static var recordingActive = false

    @Published private(set) var autoStatus = ""
    @Published private(set) var pendingCount = 0

    private var queue: [(MeetingItem, String)] = []
    private var current: (id: String, auto: Bool)?
    private var worker: Task<Void, Never>?
    private var timer: Timer?
    /// Meetings that failed this session are not retried by the idle queue (a manual retry still works).
    private var failures: [String: Int] = [:]

    func startAutoQueue() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { _ in
            Task { @MainActor in MeetingTranscriber.shared.autoTick() }
        }
        autoTick()
    }

    private func autoTick() {
        let idle = MeetingIdle.secondsSinceInput()
        if let current, current.auto {
            // Give the machine back as soon as the user returns.
            if idle < 30 || Self.recordingActive || isDictationBusy() { worker?.cancel() }
            return
        }
        guard current == nil else { return }

        Task {
            let pending = await Task.detached(priority: .utility) { MeetingTranscriber.pendingMeetings() }.value
                .filter { (failures[$0.id] ?? 0) == 0 }
            pendingCount = pending.count
            guard let next = pending.first else { autoStatus = ""; return }
            let night = (0..<6).contains(Calendar.current.component(.hour, from: Date()))
            let ready = MeetingIdle.onACPower() && !Self.recordingActive && !isDictationBusy()
                && current == nil && (idle >= 600 || (night && idle >= 120))
            if ready {
                run(next, language: TranscriptionLanguage.current.whisperCode, auto: true)
            } else {
                autoStatus = "\(pending.count) reunião(ões) sem transcrição. Serão transcritas quando o Mac ficar ocioso (10 min) ou de madrugada, na tomada."
            }
        }
    }

    /// Meetings with audio and no transcript file, newest first.
    nonisolated private static func pendingMeetings() -> [MeetingItem] {
        MeetingsStore.load().filter {
            !FileManager.default.fileExists(atPath: MeetingTranscriptStore.url(for: $0.id).path)
        }
    }

    private func transcribeTrack(_ url: URL?, speaker: String, label: String,
                                 language: String, id: String, into all: inout [MeetingSegment]) async throws {
        guard let url else { return }
        statusById[id] = .running("Convertendo \(label)...")
        let wav = try await AudioDecoder.decodeToWav(url)
        defer { try? FileManager.default.removeItem(at: wav) }

        statusById[id] = .running("Transcrevendo \(label)... 0%")
        let envelope = MeetingAudioEnergyEnvelope(wav: wav)
        let segs = try await WhisperCppCLI.transcribeSegments(wav: wav,
                                                               language: language,
                                                               suppressNonSpeech: true,
                                                               noSpeechThreshold: 0.35) { [weak self] pct in
            Task { @MainActor in self?.statusById[id] = .running("Transcrevendo \(label)... \(pct)%") }
        }
        var discardedSilenceSegments = 0
        all += segs.compactMap { segment in
            let text = MeetingGrouping.cleanText(segment.text)
            guard !text.isEmpty else { return nil }
            guard envelope?.containsSpeech(from: segment.start, to: segment.end) ?? true else {
                discardedSilenceSegments += 1
                return nil
            }
            return MeetingSegment(speaker: speaker, text: text, start: segment.start, end: segment.end)
        }
        if discardedSilenceSegments > 0 {
            NSLog("DictationApp: [MEETING] discarded %d Whisper segment(s) without audible speech on %@ track",
                  discardedSilenceSegments, label)
        }
    }
}

enum MeetingSearch {
    static func matches(_ segment: MeetingSegment, query: String) -> Bool {
        segment.text.range(of: query, options: [.caseInsensitive, .diacriticInsensitive]) != nil
            || segment.speaker.range(of: query, options: [.caseInsensitive, .diacriticInsensitive]) != nil
    }
}

import CoreGraphics
import IOKit.ps

enum MeetingIdle {
    static func secondsSinceInput() -> TimeInterval {
        CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: CGEventType(rawValue: ~0)!)
    }

    static func onACPower() -> Bool {
        guard let info = IOPSCopyPowerSourcesInfo()?.takeRetainedValue(),
              let type = IOPSGetProvidingPowerSourceType(info)?.takeUnretainedValue() else { return true }
        return (type as String) == kIOPMACPowerKey
    }
}
